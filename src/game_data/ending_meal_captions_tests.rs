use super::*;

#[test]
fn catalogs_all_progressive_caption_phases_and_slots() {
    let source = synthetic_ending_com();

    let catalog = parse_ending_meal_captions(&source).unwrap();

    assert_eq!(catalog.records.len(), 5);
    assert_eq!(
        catalog
            .records
            .iter()
            .map(|record| (record.id, record.visual_state_indices.as_slice()))
            .collect::<Vec<_>>(),
        vec![
            ("before-eating", &[1][..]),
            ("ordinary-reaction", &[2][..]),
            ("excellent-reaction", &[4][..]),
            ("bad-reaction", &[3][..]),
            ("legendary-reaction", &[2, 4][..]),
        ]
    );
    assert_eq!(
        catalog
            .records
            .iter()
            .map(|record| (
                record.id,
                record
                    .spans
                    .iter()
                    .map(|span| (span.text.as_str(), span.slot_file_offsets.len()))
                    .collect::<Vec<_>>()
            ))
            .collect::<Vec<_>>(),
        vec![
            ("before-eating", vec![("いただきま～す", 7)]),
            ("ordinary-reaction", vec![("おいしい！！", 6)]),
            ("excellent-reaction", vec![("ちょ～おいしい！！！", 10)]),
            ("bad-reaction", vec![("・・・・・・・・・・", 10)]),
            (
                "legendary-reaction",
                vec![("・・・これが・・・", 9), ("でんせつのカレ～！！！！", 12)]
            ),
        ]
    );
    assert_eq!(catalog.consumer.runtime_address, 0x2f5c);
    assert_eq!(catalog.consumer.glyph_renderer_runtime_address, 0x3076);
}

#[test]
fn rejects_caption_or_consumer_drift() {
    let mut changed_caption = synthetic_ending_com();
    changed_caption[0x4057] ^= 1;
    assert!(
        parse_ending_meal_captions(&changed_caption)
            .unwrap_err()
            .to_string()
            .contains("source text changed")
    );

    let mut changed_call = synthetic_ending_com();
    changed_call[GLYPH_RENDERER_CALL_FILE_OFFSET + 1] ^= 1;
    assert!(
        parse_ending_meal_captions(&changed_call)
            .unwrap_err()
            .to_string()
            .contains("targets")
    );

    let mut changed_visual_state = synthetic_ending_com();
    changed_visual_state[0x40f4] = 0x02;
    assert!(
        parse_ending_meal_captions(&changed_visual_state)
            .unwrap_err()
            .to_string()
            .contains("visual-state sequence changed")
    );
}

fn synthetic_ending_com() -> Vec<u8> {
    let mut bytes = vec![0x90; 0x41a7];
    bytes[INTERPRETER_FILE_OFFSET..INTERPRETER_FILE_OFFSET + INTERPRETER_SIGNATURE.len()]
        .copy_from_slice(INTERPRETER_SIGNATURE);
    let displacement = i16::try_from(
        GLYPH_RENDERER_RUNTIME_ADDRESS as isize
            - (GLYPH_RENDERER_CALL_FILE_OFFSET + COM_ORIGIN + 3) as isize,
    )
    .unwrap()
    .to_le_bytes();
    bytes[GLYPH_RENDERER_CALL_FILE_OFFSET..GLYPH_RENDERER_CALL_FILE_OFFSET + 3].copy_from_slice(&[
        0xe8,
        displacement[0],
        displacement[1],
    ]);
    for (offset, record) in source_records() {
        bytes[offset..offset + record.len()].copy_from_slice(record);
    }
    bytes
}

